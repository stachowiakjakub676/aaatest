"""Generate the UNIFAC parameter table and test fixtures from the `thermo` library.

The published original-UNIFAC parameters (subgroup R and Q, main-group interaction
parameters a_mn) are transcribed by thermo (Caleb Bell et al., MIT licence) from the literature:
Fredenslund, Jones & Prausnitz, AIChE J. 21 (1975) 1086; Fredenslund, Gmehling & Rasmussen,
Vapor-Liquid Equilibria Using UNIFAC (1977); Gmehling, Rasmussen & Fredenslund, Ind. Eng. Chem.
Process Des. Dev. 21 (1982) 118; Macedo et al. (1983); Tiegs et al. (1987); Hansen et al., Ind.
Eng. Chem. Res. 30 (1991) 2352. Nothing here is typed from memory: re-run this script to refresh.

    pip install thermo rdkit
    python scripts/generate_unifac.py

Outputs:
  packages/molecule-model/src/unifacData.ts        parameters + SMARTS fragmentation catalogue
  packages/molecule-model/test/fixtures/unifac.json  reference group assignments and activity
                                                     coefficients computed by thermo
"""

