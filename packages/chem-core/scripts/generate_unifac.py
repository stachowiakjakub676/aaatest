def solvent_smiles() -> dict[str, str]:
    text = HANSEN_TS.read_text(encoding="utf-8")
    return dict(re.findall(r'S\("([a-z0-9-]+)", "([^"]+)", ', text))


def catalog_ts() -> str:
    lines = []
    for gid in sorted(UFSG):
        g = UFSG[gid]
        if g.priority is None:
            continue
        smarts = list(g.smarts) if isinstance(g.smarts, (list, tuple)) else [g.smarts]
        lines.append(
            "  %d: { id: %d, name: %s, main: %d, R: %s, Q: %s, smarts: %s, priority: %d, hydrogens: %d, hydrogenFromSmarts: %s },"
            % (gid, gid, json.dumps(g.group), g.main_group_id, repr(float(g.R)), repr(float(g.Q)), json.dumps(smarts), g.priority, (g.atoms or {}).get("H", 0), "true" if g.hydrogen_from_smarts else "false")
        )
    return "\n".join(lines)


def main() -> None:
    mains = "\n".join("  %d: %s," % (mid, json.dumps(UFMG[mid][0])) for mid in sorted(UFMG))
    inter = []
    for m in sorted(UFIP):
        for n in sorted(UFIP[m]):
            inter.append('  "%d-%d": %s,' % (m, n, repr(float(UFIP[m][n]))))
    DATA_TS.write_text(
        "/**\n * Original UNIFAC (VLE) parameters and the SMARTS fragmentation catalogue. GENERATED by\n"
        " * packages/chem-core/scripts/generate_unifac.py from the thermo library %s (MIT), which transcribes\n"
        " * the published tables (Fredenslund et al. 1975/1977; Gmehling et al. 1982; Macedo et al. 1983;\n"
        " * Tiegs et al. 1987; Hansen et al. 1991). Do not edit by hand.\n */\n\n"
        "export interface UnifacSubgroup {\n  id: number;\n  name: string;\n  /** Main group id (interaction parameters are per main group). */\n  main: number;\n  R: number;\n  Q: number;\n"
        "  /** One or more SMARTS patterns; any match counts. */\n  smarts: string[];\n  /** Higher priority wins when patterns overlap. */\n  priority: number;\n"
        "  /** Hydrogens the group accounts for (used to verify a fragmentation is complete). */\n  hydrogens: number;\n  /** Count hydrogens from the matched atoms instead of the fixed number. */\n  hydrogenFromSmarts: boolean;\n}\n\n"
        "export const UNIFAC_SUBGROUPS: Record<number, UnifacSubgroup> = {\n%s\n};\n\n"
        "export const UNIFAC_MAIN_GROUPS: Record<number, string> = {\n%s\n};\n\n"
        "/** a_mn in kelvin, keyed \"m-n\" by main group; a_mn ≠ a_nm. */\n"
        "export const UNIFAC_INTERACTIONS: Record<string, number> = {\n%s\n};\n" % (thermo.__version__, catalog_ts(), mains, "\n".join(inter)),
        encoding="utf-8",
    )

    catalog = [g for g in UFSG.values() if g.priority is not None]
    assignments = []
    for name, smi in list(solvent_smiles().items()) + list(EXTRA_SMILES.items()):
        counts, groups, matched, success, status = smarts_fragment_priority(catalog=catalog, smi=smi)
        assignments.append({"name": name, "smiles": smi, "success": bool(success), "groups": {str(k): v for k, v in sorted(counts.items())} if success else {}, "status": status})

    gammas = []
    for name, groups, T, xs in GAMMA_CASES:
        ge = UNIFAC.from_subgroups(T=T, xs=xs, chemgroups=groups, subgroups=UFSG, interaction_data=UFIP, version=0)
        gammas.append({"name": name, "groups": [{str(k): v for k, v in g.items()} for g in groups], "T": T, "xs": xs, "gammas": ge.gammas()})

    FIXTURE.write_text(json.dumps({"thermo": thermo.__version__, "assignments": assignments, "gammas": gammas}, indent=1), encoding="utf-8")
    ok = sum(1 for a in assignments if a["success"])
    print(f"wrote {DATA_TS.relative_to(ROOT)} ({len(catalog)} subgroups, {len(inter)} interactions) and {FIXTURE.relative_to(ROOT)} ({ok}/{len(assignments)} fragmentations succeeded)")
    for a in assignments:
        if not a["success"]:
            print("  not fragmented:", a["name"], a["status"])


if __name__ == "__main__":
    sys.exit(main())
